def help_text(key: str) -> str:
    return HELP_TEXTS.get(key, "لو محتارة في الاختيار ده، جرّبيه وأنا هافضل معاكي خطوة بخطوة.")


def render_context_help(key: str, *, label: str = "💬 ده بيعمل إيه؟") -> None:
    text = help_text(key)
    with st.expander(label, expanded=False):
        st.write(text)


